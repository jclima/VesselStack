#!/bin/bash
# Regenerate boat-chat/requirements.lock, the hash-pinned lock that install.sh and
# prepare-offline-bundle.sh install with `pip --require-hashes --only-binary=:all:`.
#
#   update-requirements-lock.sh [--python-version X.Y]... [--platform TAG]...
#
# Needs network and pip. For every Python version and platform tag it runs
# `pip download -r boat-chat/requirements.txt --only-binary=:all:` into a scratch
# directory, hashes every wheel it fetched and writes one `name==version` entry
# with all of the hashes. Defaults cover Python 3.11, 3.12 and 3.13 on Linux
# aarch64 (Raspberry Pi OS 64-bit) and x86_64 (home lab). Source distributions
# are never fetched, so every dependency must publish wheels for these targets.
#
# The lock is trust-on-first-use against PyPI: review the diff, and compare the
# hashes with the digests PyPI shows for the release, before committing it. It
# records the sha256 of requirements.txt; tests/test_requirements_lock.py fails
# when requirements.txt changes without a regenerated lock.

set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
REQUIREMENTS="$ROOT/boat-chat/requirements.txt"
LOCK="$ROOT/boat-chat/requirements.lock"
PYTHON_VERSIONS=()
PLATFORMS=()

while [ $# -gt 0 ]; do
    case "$1" in
        --python-version) PYTHON_VERSIONS+=("$2"); shift 2 ;;
        --platform) PLATFORMS+=("$2"); shift 2 ;;
        -h|--help) sed -n '2,18p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done
[ "${#PYTHON_VERSIONS[@]}" -gt 0 ] || PYTHON_VERSIONS=(3.11 3.12 3.13)
# Each group is one architecture; --platform tags given explicitly form one group.
TAG_GROUPS=()
if [ "${#PLATFORMS[@]}" -eq 0 ]; then
    TAG_GROUPS=("manylinux2014_aarch64 manylinux_2_17_aarch64 manylinux_2_28_aarch64"
        "manylinux2014_x86_64 manylinux_2_17_x86_64 manylinux_2_28_x86_64")
else
    TAG_GROUPS=("${PLATFORMS[*]}")
fi

SCRATCH=$(mktemp -d)
trap 'rm -rf -- "$SCRATCH"' EXIT
# One download per architecture group: pip fetches only the best-ranked wheel for
# a set of tags, so mixing architectures would leave one of them without a hash.
for version in "${PYTHON_VERSIONS[@]}"; do
    for group in "${TAG_GROUPS[@]}"; do
        platform_args=()
        for platform in $group; do platform_args+=(--platform "$platform"); done
        python3 -m pip download --disable-pip-version-check --only-binary=:all: \
            --python-version "$version" --implementation cp "${platform_args[@]}" \
            --dest "$SCRATCH" -r "$REQUIREMENTS"
    done
done

python3 -I - "$SCRATCH" "$REQUIREMENTS" "$LOCK" <<'PY'
import hashlib, pathlib, re, sys

scratch, requirements, lock = (pathlib.Path(a) for a in sys.argv[1:4])
projects = {}
for wheel in sorted(scratch.iterdir()):
    if wheel.suffix != '.whl':
        sys.exit(f'refusing non-wheel download: {wheel.name}')
    name, version = wheel.name.split('-')[:2]
    name = re.sub(r'[-_.]+', '-', name).lower()
    projects.setdefault(name, {}).setdefault(version, set()).add(hashlib.sha256(wheel.read_bytes()).hexdigest())
lines = [
    '# Generated by scripts/update-requirements-lock.sh - do not edit by hand.',
    '# requirements-sha256: ' + hashlib.sha256(requirements.read_bytes()).hexdigest(),
]
for name in sorted(projects):
    versions = projects[name]
    if len(versions) != 1:
        sys.exit(f'{name} resolved to several versions {sorted(versions)}; pin it in requirements.txt')
    (version, hashes), = versions.items()
    lines.append(f'{name}=={version} \\')
    ordered = sorted(hashes)
    lines.extend(f'    --hash=sha256:{h}' + (' \\' if i < len(ordered) - 1 else '') for i, h in enumerate(ordered))
lock.write_text('\n'.join(lines) + '\n')
print(f'Wrote {lock} ({len(projects)} project(s))')
PY
