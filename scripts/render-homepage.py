def parse_env_line(line: str) -> tuple[str, str] | None:
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    if line.startswith("export "):
        line = line[7:].lstrip()
    key, sep, value = line.partition("=")
    if not sep or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
        return None
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        value = value[1:-1]
    return key, value


def read_env(config_dir: Path) -> dict[str, str]:
    """Allow-listed values only; later files override earlier ones."""
    result: dict[str, str] = {}
    for name in ENV_FILES:
        path = config_dir / name
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for raw in text.splitlines():
            parsed = parse_env_line(raw)
            if parsed and parsed[0] in VESSELSTACK_KEYS:
                result[parsed[0]] = parsed[1]
    return result


def bind_kind(address: str) -> str:
    address = address.strip()
    if address in ("", "0.0.0.0", "::", "*"):
        return "all"
    if address.startswith("127.") or address in ("::1", "localhost"):
        return "loopback"
    return "other"


def port_of(value: str | None, default: int) -> int:
    try:
        port = int(str(value))
    except (TypeError, ValueError):
        return default
    return port if 1 <= port <= 65535 else default


def url_parts(value: str | None, default_port: int) -> tuple[str, int]:
    try:
        parts = urlsplit(value or "")
        return parts.hostname or "127.0.0.1", parts.port or default_port
    except ValueError:
        return "127.0.0.1", default_port


def disabled_components(env: dict[str, str]) -> set[str]:
    return {item.strip() for item in env.get("VESSELSTACK_DISABLED_COMPONENTS", "").split(",") if item.strip()}


def detect_hostname() -> str:
    name = socket.gethostname().split(".")[0].strip()
    return name if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,62}", name) else "localhost"


def detect_addresses() -> list[str]:
    try:
        output = subprocess.run(
            ["ip", "-4", "-o", "addr", "show", "scope", "global"],
            capture_output=True, text=True, timeout=5, check=False,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return []
    return re.findall(r"inet (\d+\.\d+\.\d+\.\d+)/", output)


def allowed_hosts(env: dict[str, str], hostname: str, addresses: list[str]) -> str:
    """Host headers Homepage accepts: boat names, current IPv4s and loopback.

    Homepage compares the whole Host header, which carries the port only when it is
    not the scheme default, so ":port" is added exactly when the port is not 80.
    """
    port = port_of(env.get("HOMEPAGE_PORT"), 80)
    names: list[str] = []
    for name in (f"{hostname}.local", hostname, *addresses, "localhost", "127.0.0.1"):
        if name and name not in names:
            names.append(name)
    entries = [name if port == 80 else f"{name}:{port}" for name in names]
    for extra in env.get("HOMEPAGE_ALLOWED_HOSTS_EXTRA", "").split(","):
        extra = extra.strip()
        if extra and HOST_ENTRY.fullmatch(extra) and extra not in entries:
            entries.append(extra)
    return ",".join(entries)


def q(value: str) -> str:
    """A JSON string is a valid YAML double-quoted scalar."""
    return json.dumps(value, ensure_ascii=True)


class Tile:
    def __init__(self, name: str, group: str, description: str, href: str | None = None,
                 monitor: str | None = None) -> None:
        self.name, self.group, self.description = name, group, description
        self.href, self.monitor = href, monitor


def build_tiles(env: dict[str, str], hostname: str) -> list[Tile]:
    disabled = disabled_components(env)
    web_bind = env.get("VESSELSTACK_WEB_BIND_ADDRESS", "0.0.0.0")
    data_bind = env.get("VESSELSTACK_DATA_BIND_ADDRESS", "127.0.0.1")
    host = f"{hostname}.local"
    tiles: list[Tile] = []

    def link(name: str, group: str, description: str, port: int, bind: str, *,
             tunnel: str = "", path: str = "", monitor_host: bool = True) -> None:
        kind = bind_kind(bind)
        if kind == "loopback":
            note = tunnel or "Only reachable on this device (use an SSH tunnel)"
            tiles.append(Tile(name, group, f"{description}. {note}"))
            return
        href = f"http://{host}:{port}{path}"
        monitor = f"http://host.docker.internal:{port}" if kind == "all" and monitor_host else None
        tiles.append(Tile(name, group, description, href, monitor))

    chat_port = effective_chat_port(env)
    link("Boat Chat", "Boat", "Ask your boat", chat_port, env.get("BOAT_CHAT_HOST", "0.0.0.0"),
         tunnel="Limited to this device; share it with: sudo vesselstackctl lan dashboards")

    ha_host, ha_port = url_parts(env.get("HOME_ASSISTANT_URL"), 8123)
    if "homeassistant" not in disabled and bind_kind(ha_host) == "loopback":
        link("Home Assistant", "Boat", "Automation and history", ha_port,
             env.get("HOMEASSISTANT_BIND_ADDRESS", "0.0.0.0"))

    if env.get("SIGNALK_MODE", "existing") in ("docker", "native"):
        _, sk_port = url_parts(env.get("SIGNALK_URL"), 3000)
        link("Signal K", "Boat", "Boat data server", sk_port, "0.0.0.0")
    else:
        # An existing Signal K server elsewhere on the network: link it (no monitoring).
        # Only scheme, host and port are used, so credentials or paths in the URL never appear.
        try:
            sk = urlsplit(env.get("SIGNALK_URL", ""))
            sk_host, sk_port = sk.hostname, sk.port
        except ValueError:
            sk, sk_host, sk_port = None, None, None
        if sk and sk.scheme in ("http", "https") and sk_host and bind_kind(sk_host) != "loopback" \
                and re.fullmatch(r"[A-Za-z0-9.-]+|[0-9A-Fa-f:]+", sk_host):
            shown = f"[{sk_host}]" if ":" in sk_host else sk_host
            tiles.append(Tile("Signal K", "Boat", "Boat data server (on another computer)",
                              f"{sk.scheme}://{shown}" + (f":{sk_port}" if sk_port else "")))

    if env.get("AIS_ENABLE", "false") == "true":
        link("AIS", "Boat", "Nearby vessels", port_of(env.get("AIS_WEB_PORT"), 8100), "0.0.0.0")

    if env.get("DISPLAYS_ENABLE", "false") == "true":
        panel_bind = env.get("CONTROL_PANEL_HOST", "127.0.0.1")
        panel_port = port_of(env.get("CONTROL_PANEL_PORT"), 8780)
        link("Displays", "Boat", "Open the Displays tab of the Control Panel", panel_port, panel_bind,
             tunnel="Open the Control Panel through an SSH tunnel, then its Displays tab",
             path="/?tab=displays", monitor_host=False)

    if env.get("NODERED_ENABLE", "false") == "true":
        link("Node-RED", "Data", "Flow editor (sign-in required)", port_of(env.get("NODERED_PORT"), 1880),
             env.get("NODERED_BIND_ADDRESS") or "127.0.0.1",
             tunnel="Limited to this device; reach it with an SSH tunnel to the Node-RED port")

    if "grafana" not in disabled:
        link("Grafana", "Data", "Dashboards", port_of(env.get("GRAFANA_PORT"), 43000), web_bind)
    if bind_kind(data_bind) != "loopback":
        if "influxdb" not in disabled:
            link("InfluxDB", "Data", "Time-series database (token required)",
                 port_of(env.get("INFLUXDB_PORT"), 8086), data_bind)
        if "prometheus" not in disabled:
            link("Prometheus", "Data", "Metrics (no login)", port_of(env.get("PROMETHEUS_PORT"), 9090), data_bind)

    panel_bind = env.get("CONTROL_PANEL_HOST", "127.0.0.1")
    panel_port = port_of(env.get("CONTROL_PANEL_PORT"), 8780)
    if bind_kind(panel_bind) == "loopback":
        tiles.append(Tile("Control Panel", "System",
                          f"Settings and updates. Reach it with: ssh -L {panel_port}:127.0.0.1:{panel_port} "
                          "USER@HOST (SSH tunnel), or: sudo vesselstackctl panel-access lan"))
    else:
        link("Control Panel", "System", "Settings and updates (token required)", panel_port, panel_bind)
    return tiles


def services_yaml(tiles: list[Tile]) -> str:
    lines: list[str] = []
    groups: list[str] = []
    for tile in tiles:
        if tile.group not in groups:
            groups.append(tile.group)
    for group in groups:
        lines.append(f"- {q(group)}:")
        for tile in tiles:
            if tile.group != group:
                continue
            lines.append(f"    - {q(tile.name)}:")
            if tile.href:
                lines.append(f"        href: {q(tile.href)}")
            lines.append(f"        description: {q(tile.description)}")
            if tile.monitor:
                lines.append(f"        siteMonitor: {q(tile.monitor)}")
    return "\n".join(lines) + "\n"


