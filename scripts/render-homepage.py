def valid_custom_list(text: str) -> str | None:
    """Return None when ``text`` is an acceptable top-level YAML list, else the reason.

    Without a YAML parser in the standard library this checks structure only: the
    file must be small UTF-8 text, indented with spaces, and every content line at
    column 0 must start a list item ("- ").
    """
    if len(text.encode("utf-8")) > MAX_CUSTOM_BYTES:
        return "file is larger than 256 KiB"
    if "\x00" in text:
        return "file contains a NUL byte"
    seen_item = False
    for number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if line.startswith("\t") or re.match(r" *\t", line):
            return f"line {number} is indented with a tab"
        if not line[0].isspace():
            if line.startswith("- ") or line.rstrip() == "-":
                seen_item = True
            else:
                return f"line {number} is not part of a top-level list"
        elif not seen_item:
            return f"line {number} is indented before the first list item"
    return None


def read_custom(path: Path) -> tuple[str, str | None]:
    """Text of a user file and the reason it is unusable (if any); never raises."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0))
    except OSError as error:
        return "", f"cannot open {path}: {error.strerror}"
    try:
        with os.fdopen(fd, "rb") as handle:
            data = handle.read(MAX_CUSTOM_BYTES + 1)
    except OSError as error:
        return "", f"cannot read {path}: {error.strerror}"
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return "", "file is not UTF-8"
    return text, valid_custom_list(text)


def open_dir(path: Path, mode: int = 0o755) -> int:
    """Create (if needed) and open a directory without following a symbolic link."""
    if path.is_symlink():
        raise OSError(f"refusing symlinked directory: {path}")
    path.mkdir(mode=mode, parents=True, exist_ok=True)
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0))
    try:
        # mkdir's mode is masked by the caller's umask (vesselstackctl runs with 077), which
        # would leave the container's service user unable to read the config; also repairs
        # directories created by an earlier run.
        os.fchmod(fd, mode)
    except BaseException:
        os.close(fd)
        raise
    return fd


def atomic_write(dir_fd: int, name: str, data: bytes, mode: int = 0o644) -> None:
    """Temp file + fsync + rename inside an already opened directory (no-follow)."""
    temp = f".{name}.tmp.{os.getpid()}"
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    try:
        os.unlink(temp, dir_fd=dir_fd)
    except FileNotFoundError:
        pass
    fd = os.open(temp, flags, mode, dir_fd=dir_fd)
    try:
        with os.fdopen(fd, "wb") as handle:
            os.fchmod(handle.fileno(), mode)  # independent of the caller's umask
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp, name, src_dir_fd=dir_fd, dst_dir_fd=dir_fd)
    except BaseException:
        try:
            os.unlink(temp, dir_fd=dir_fd)
        except OSError:
            pass
        raise
    os.fsync(dir_fd)


def create_once(dir_fd: int, name: str, text: str) -> None:
    """Create a user-editable file when absent; never touch an existing one."""
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    try:
        fd = os.open(name, flags, 0o644, dir_fd=dir_fd)
    except FileExistsError:
        return
    with os.fdopen(fd, "wb") as handle:
        os.fchmod(handle.fileno(), 0o644)
        handle.write(text.encode("utf-8"))
        handle.flush()
        os.fsync(handle.fileno())


def render(root: Path, hostname: str, brand_icon: Path | None) -> list[str]:
    warnings: list[str] = []
    env = read_env(root / "config")
    endpoint = load_effective_chat_endpoint(root, env=os.environ)
    env["BOAT_CHAT_HOST"] = endpoint["host"]
    env["BOAT_CHAT_PORT"] = str(endpoint["port"])
    out_dir = root / "config" / "homepage"
    custom_dir = root / "config" / "homepage-custom"
    icons_dir = root / "config" / "homepage-icons"

    custom_fd = open_dir(custom_dir)
    try:
        create_once(custom_fd, "services.yaml", CUSTOM_SERVICES_TEMPLATE)
        create_once(custom_fd, "bookmarks.yaml", CUSTOM_BOOKMARKS_TEMPLATE)
    finally:
        os.close(custom_fd)

    services = services_yaml(build_tiles(env, hostname))
    custom_services, problem = read_custom(custom_dir / "services.yaml")
    if problem:
        warnings.append(f"Skipping {custom_dir / 'services.yaml'}: {problem}")
    elif any(l.strip() and not l.lstrip().startswith("#") for l in custom_services.splitlines()):
        services += "\n" + custom_services.rstrip("\n") + "\n"
    bookmarks = "---\n# Add bookmarks in config/homepage-custom/bookmarks.yaml\n[]\n"
    custom_bookmarks, problem = read_custom(custom_dir / "bookmarks.yaml")
    if problem:
        warnings.append(f"Skipping {custom_dir / 'bookmarks.yaml'}: {problem}")
    elif any(l.strip() and not l.lstrip().startswith("#") for l in custom_bookmarks.splitlines()):
        bookmarks = custom_bookmarks.rstrip("\n") + "\n"

    icons_fd = open_dir(icons_dir)
    try:
        has_logo = brand_icon is not None and brand_icon.is_file()
        if has_logo:
            atomic_write(icons_fd, "vesselstack.png", brand_icon.read_bytes())
        else:
            warnings.append("Brand icon not found; using a text heading")
    finally:
        os.close(icons_fd)

    theme = homepage_option(env, "HOMEPAGE_THEME")
    columns = {"compact": 2, "standard": 3, "wide": 4}[homepage_option(env, "HOMEPAGE_COLUMNS")]
    heading = env.get("BOAT_NAME", "").strip() if homepage_option(env, "HOMEPAGE_HEADING") == "boat" else ""
    heading = heading or "VesselStack"
    clock = homepage_option(env, "HOMEPAGE_CLOCK")
    files = {
        "settings.yaml": settings_yaml(heading, theme, columns, has_logo),
        "services.yaml": services,
        "widgets.yaml": widgets_yaml(heading, clock, has_logo),
        "bookmarks.yaml": bookmarks,
        "docker.yaml": DOCKER_YAML,
        "kubernetes.yaml": KUBERNETES_YAML,
        "proxmox.yaml": PROXMOX_YAML,
        "custom.css": CUSTOM_CSS + (LIGHT_CSS if theme == "light" else ""),
        "custom.js": CUSTOM_JS_TEMPLATE.replace("__HOSTNAME__", json.dumps(f"{hostname}.local")),
    }
    out_fd = open_dir(out_dir)
    try:
        for name, text in files.items():
            atomic_write(out_fd, name, text.encode("utf-8"))
    finally:
        os.close(out_fd)

    return warnings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("render", "allowed-hosts"))
    parser.add_argument("--root", default=os.environ.get("VESSELSTACK_ROOT", "/opt/vesselstack"))
    parser.add_argument("--hostname")
    parser.add_argument("--addresses", help="comma-separated IPv4 addresses (default: detected)")
    parser.add_argument("--brand-icon", help="PNG copied to the icons directory")
    args = parser.parse_args(argv)
    root = Path(args.root)
    hostname = args.hostname or detect_hostname()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,62}", hostname):
        parser.error(f"invalid --hostname: {hostname!r}")
    if args.addresses is not None:
        addresses = [a for a in args.addresses.split(",") if re.fullmatch(r"\d+\.\d+\.\d+\.\d+", a)]
    else:
        addresses = detect_addresses()
    if args.command == "allowed-hosts":
        print(allowed_hosts(read_env(root / "config"), hostname, addresses))
        return 0
    icon = Path(args.brand_icon) if args.brand_icon else root / "installer" / "brand" / "icon.png"
    try:
        for warning in render(root, hostname, icon):
            print(f"WARN: {warning}", file=sys.stderr)
    except OSError as error:
        print(f"Cannot write the home page configuration: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
